/** Choice の criteria にそのまま渡す形（大分類）。children は落とす。 */
export function majorCriteria() {
  return Object.fromEntries(
    Object.entries(TAXONOMY).map(([name, node]) => [
      name,
      { what: node.what, not_for: node.not_for, examples: node.examples },
    ])
  );
}

/** Choice の criteria にそのまま渡す形（ある大分類の小分類）。 */
export function minorCriteria(major) {
  return TAXONOMY[major]?.children ?? {};
}

